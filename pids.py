# coding: utf-8
import math


def _u16(b, idx=0):
    if len(b) < idx + 2:
        return None
    return (b[idx] << 8) | b[idx + 1]


def _s16(b, idx=0):
    v = _u16(b, idx)
    if v is None:
        return None
    return v - 65536 if v >= 32768 else v


def _u8(b, idx=0):
    if len(b) <= idx:
        return None
    return b[idx]


def _knock_cil(b, idx):
    v = _s16(b, idx)
    if v is None:
        return 0.0
    return round(v * 0.1, 1)


def _knock_max_4cil(b):
    vals = [_knock_cil(b, 8), _knock_cil(b, 10), _knock_cil(b, 12), _knock_cil(b, 14)]
    return min(vals)


